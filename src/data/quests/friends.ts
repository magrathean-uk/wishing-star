// The eight friend-hero lines (finishing one unlocks that friend as a hero at the mirror) and the jobs on the board.
// A friend hero unlocks only after their stand-in has arrived, so every line requires that.
// Phase 2 (package 43b): half the words. Woody's Wanted posters and eight small jobs are board jobs (`board: true`):
// the board in the Square lists up to 3 at a time, each a picture, a number and at most 6 words. Taken from the
// board, a job has no talk; it ends on its last step and pays at once (and, as a job, a prize ticket).
import type { QuestDef, Step } from '../../core/types.ts';

type Q = Omit<QuestDef, 'kind'>;
const friend = (q: Q): QuestDef => ({ kind: 'friend', ...q });
/** Woody's Wanted posters: fight jobs that come round again. */
const poster = (
  id: string,
  name: string,
  mob: string,
  n: number,
  pay: number,
  requires: QuestDef['requires'],
): QuestDef => ({
  id,
  name,
  kind: 'bounty',
  board: true,
  region: 'home',
  giver: 'woody',
  style: 'fight',
  group: 'toys',
  repeat: true,
  requires,
  steps: [{ t: 'defeat', mob, n, goal: name }],
  rewards: { emeralds: pay, claw: 1 },
  visible: 'One more go on the claw machine.',
});
/** A small one-off job: gather and deliver, or find a place. Its name is what the board shows. */
const job = (
  id: string,
  name: string,
  giver: string,
  region: string,
  style: NonNullable<QuestDef['style']>,
  requires: QuestDef['requires'],
  step: Step,
  rewards: QuestDef['rewards'],
  visible: string,
  more: Partial<QuestDef> = {},
): QuestDef => ({
  id,
  name,
  kind: 'bounty',
  board: true,
  region,
  giver,
  style,
  requires,
  steps: [{ ...step, goal: name }],
  rewards,
  visible,
  ...more,
});

/** Package 47b: an island project, a board job with one build site ('<site>', quest 'p_<site>'). The Minions build it. */
const project = (
  site: string,
  name: string,
  region: string,
  requires: QuestDef['requires'],
  rewards: QuestDef['rewards'],
): QuestDef => ({
  id: 'p_' + site,
  name,
  kind: 'side',
  board: true,
  region,
  giver: 'kevin',
  group: 'minions',
  style: 'craft',
  requires,
  steps: [{ t: 'site', site, goal: name }],
  rewards,
  visible: `The ${BUILT[site] ?? site} stays built.`,
});
