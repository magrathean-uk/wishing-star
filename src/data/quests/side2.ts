function fishBoard(): QuestDef[] {
  const part = (n: number, kinds: string[], requires: QuestDef['requires'], rewards: QuestDef['rewards']) =>
    side({
      id: 'fb_' + n,
      name: "{dad}'s fish board",
      region: 'bay',
      giver: 'dad',
      group: 'family',
      style: 'explore',
      auto: true,
      requires,
      steps: kinds.map((kind) => ({ t: 'fish' as const, kind })),
      rewards,
      visible: "{dad}'s fish board has more ticks on it.",
    });
  return [
    part(1, ['sardine', 'trout', 'minnow'], { done: 'ch4' }, { emeralds: 10 }),
    part(2, ['mackerel', 'goldfish', 'pond_carp'], { done: 'fb_1' }, { give: { mermaid_fountain: 1 } }),
    part(
      3,
      ['puffer_fish', 'moon_jelly', 'salmon', 'glow_fish'],
      { done: ['fb_2', 'ch5'] },
      {
        emeralds: 30,
        give: { trophy_star: 1 },
        flags: ['trophy_fish'],
      },
    ),
  ];
}

function cupPrizes(): QuestDef[] {
  const PRIZE: Record<string, string> = {
    keepy: 'toy_drum',
    puddles: 'rainbow_rug',
    hide: 'painting_star',
    race: 'toy_rocket',
    claw: 'alien_plush',
    snowball: 'snowman_item',
    minecart: 'toy_train',
    targets: 'toy_robot',
  };
  return Object.entries(PRIZE).map(([game, item]) =>
    side({
      id: 'cup_prize_' + game,
      name: 'Gold cup prize',
      region: 'home',
      giver: 'hamm',
      group: 'toys',
      style: 'explore',
      auto: true,
      requires: { flag: 'cup_' + game },
      onStart: { give: { [item]: 1 } },
      // held at once, so the step is done on the next check
      steps: [{ t: 'craft', item }],
      visible: 'A gold cup prize stands in her house.',
    }),
  );
}
